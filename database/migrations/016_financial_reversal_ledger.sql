  ON financial_reversal_items(brand_network_earning_id);

CREATE INDEX IF NOT EXISTS idx_financial_reversal_items_creator_earning_claim_id
  ON financial_reversal_items(creator_earning_claim_id);

CREATE INDEX IF NOT EXISTS idx_financial_reversal_items_affected_creator_id
  ON financial_reversal_items(affected_creator_id);

CREATE INDEX IF NOT EXISTS idx_financial_reversal_items_affected_brand_id
  ON financial_reversal_items(affected_brand_id);

CREATE INDEX IF NOT EXISTS idx_financial_reversal_items_offset_required
  ON financial_reversal_items(offset_required);

COMMENT ON TABLE financial_reversal_events IS
  'Immutable PartnerLinks refund/chargeback/dispute/manual-adjustment event ledger. Observability/accounting infrastructure only; does not apply reversals or move money by itself.';

COMMENT ON TABLE financial_reversal_items IS
  'Line-item reversal ledger linking reversal events to affected conversion, network earning, brand earning, or claim rows. Does not mutate payout behavior by itself.';

COMMENT ON COLUMN financial_reversal_events.evidence IS
  'Minimal non-sensitive evidence only. Do not store full Shopify, Stripe, customer, card, or payment payloads here by default.';

